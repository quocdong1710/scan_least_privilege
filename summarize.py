#!/usr/bin/env python3
"""AWS IAM Least Privilege Report Summarizer.

Reads JSON reports generated by scan.py and produces human-readable executive summaries,
highlighting excess permissions, escalation risks, and actionable remediation steps.
"""

import os
import sys
import json
import html
import argparse
from datetime import datetime

# Configure UTF-8 encoding for Windows console
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass


def format_header(title, width=70, char="="):
    return f"\n{char * width}\n  {title}\n{char * width}"


def load_report(filepath):
    if not os.path.exists(filepath):
        print(f"[!] Error: File not found: {filepath}")
        sys.exit(1)
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        print(f"[!] Error reading JSON file: {e}")
        sys.exit(1)


def generate_summary(data, only_users=False, critical_only=False, max_sample_services=8):
    findings = data.get("findings", [])
    if only_users:
        findings = [f for f in findings if f.get("principal_type") == "User"]

    summary_blocks = []
    
    # Overview metadata
    report_time = data.get("report_time", "N/A")
    source = data.get("source", "N/A")
    stages = ", ".join(data.get("stages_run", ["N/A"]))
    sev = data.get("severity_summary", {})
    
    overview = {
        "report_time": report_time,
        "source": source,
        "stages": stages,
        "total_principals": len(findings),
        "critical": sev.get("critical", 0),
        "high": sev.get("high", 0),
        "medium": sev.get("medium", 0),
        "low": sev.get("low", 0),
    }

    principal_summaries = []

    for p in findings:
        ptype = p.get("principal_type", "Unknown")
        pname = p.get("principal_name", "Unknown")
        arn = p.get("arn", "")
        
        escs = p.get("escalation_paths", [])
        wildcards = p.get("wildcard_findings", [])
        res_wildcards = p.get("resource_wildcard_findings", [])
        unused = p.get("unused_services", [])
        denied = p.get("denied_actions", [])
        sources = p.get("permission_sources", [])

        never_used = [s for s in unused if s.get("status") == "never_used"]
        inactive = [s for s in unused if s.get("status") == "inactive"]

        # Filter out if critical_only requested and no critical/high issues
        has_critical_or_high = bool(escs or wildcards or res_wildcards)
        if critical_only and not has_critical_or_high:
            continue

        item = {
            "type": ptype,
            "name": pname,
            "arn": arn,
            "sources": sources,
            "denied": denied,
            "escalations": escs,
            "wildcards": wildcards,
            "resource_wildcards": res_wildcards,
            "never_used": never_used,
            "inactive": inactive,
        }
        principal_summaries.append(item)

    return overview, principal_summaries


def render_console(overview, principals, max_sample_services=6):
    lines = []
    lines.append(format_header("TỔNG KẾT BÁO CÁO AN TOÀN IAM & LEAST PRIVILEGE", 75, "="))
    lines.append(f"  Thời gian quét : {overview['report_time']}")
    lines.append(f"  Nguồn dữ liệu  : {overview['source']}")
    lines.append(f"  Giai đoạn chạy : {overview['stages']}")
    lines.append(f"  Số đối tượng vi phạm: {len(principals)}")
    lines.append("-" * 75)
    lines.append(
        f"  MỨC ĐỘ RỦI RO: "
        f"CRITICAL: {overview['critical']} | "
        f"HIGH: {overview['high']} | "
        f"MEDIUM: {overview['medium']} | "
        f"LOW: {overview['low']}"
    )
    lines.append("=" * 75)

    if not principals:
        lines.append("\n  [✓] Không có phát hiện nào thỏa mãn tiêu chí lọc.")
        return "\n".join(lines)

    lines.append("\n" + format_header("CHI TIẾT CÁC ĐỐI TƯỢNG CẦN THU HỒI / ĐIỀU CHỈNH QUYỀN", 75, "-"))

    for p in principals:
        icon = "👤" if p["type"] == "User" else "🛡️"
        lines.append(f"\n{icon} [{p['type'].upper()}] {p['name']}")
        lines.append(f"   ARN: {p['arn']}")

        # Permission sources
        if p["sources"]:
            lines.append("   📌 Nguồn cấp quyền:")
            for s in p["sources"]:
                stype = s.get("source_type", "")
                p_name = s.get("policy_name", "unknown")
                if stype == "group_managed":
                    lines.append(f"      - Kế thừa từ Group [{s.get('group_name')}] -> Managed Policy [{p_name}]")
                elif stype == "group_inline":
                    lines.append(f"      - Kế thừa từ Group [{s.get('group_name')}] -> Inline Policy [{p_name}]")
                elif stype == "managed":
                    lines.append(f"      - Gắn trực tiếp Managed Policy [{p_name}]")
                elif stype == "inline":
                    lines.append(f"      - Gắn trực tiếp Inline Policy [{p_name}]")

        # Denied actions
        if p["denied"]:
            lines.append(f"   ⛔ Quyền bị chặn tường minh (Explicit Deny): {len(p['denied'])} hành động {p['denied'][:4]}")

        # Escalation paths
        if p["escalations"]:
            lines.append(f"   🚨 NGUY CƠ LEO THANG ĐẶC QUYỀN ADMIN: {len(p['escalations'])} kịch bản")
            for esc in p["escalations"][:4]:
                lines.append(f"      • [{esc.get('severity').upper()}] {esc.get('escalation_path')}: {esc.get('description')}")
            if len(p["escalations"]) > 4:
                lines.append(f"      • ... và {len(p['escalations']) - 4} kịch bản khác.")

        # Wildcards
        if p["wildcards"]:
            lines.append("   ⚠️  CẤP QUYỀN TOÀN PHẦN (WILDCARD):")
            for w in p["wildcards"]:
                lines.append(f"      • Action: {w.get('action')} ({w.get('finding')})")

        # Resource wildcards
        if p["resource_wildcards"]:
            lines.append(f"   🎯 PHẠM VI TÀI NGUYÊN QUÁ RỘNG (Resource: * trên hành động nhạy cảm): {len(p['resource_wildcards'])} quyền")
            for rw in p["resource_wildcards"][:4]:
                lines.append(f"      • {rw.get('finding')}")
            if len(p["resource_wildcards"]) > 4:
                lines.append(f"      • ... và {len(p['resource_wildcards']) - 4} quyền khác cần thu hẹp ARN.")

        # Unused services
        if p["never_used"]:
            sample_never = [s.get("service_name", "") for s in p["never_used"][:max_sample_services]]
            lines.append(f"   ❌ DƯ THỪA (CHƯA TỪNG DÙNG): {len(p['never_used'])} dịch vụ")
            lines.append(f"      Ví dụ: {', '.join(sample_never)}")
            if len(p["never_used"]) > max_sample_services:
                lines.append(f"      (Và {len(p['never_used']) - max_sample_services} dịch vụ khác cần gỡ bỏ khỏi policy)")

        if p["inactive"]:
            sample_inactive = [f"{s.get('service_name')} ({s.get('days_inactive')} ngày)" for s in p["inactive"][:4]]
            lines.append(f"   ⏳ DỊCH VỤ BỎ HOANG (>90 ngày): {len(p['inactive'])} dịch vụ")
            lines.append(f"      Ví dụ: {', '.join(sample_inactive)}")

        lines.append("   " + "." * 70)

    return "\n".join(lines)


