def main():
    parser = argparse.ArgumentParser(
        description="AWS IAM Least Privilege Report Summarizer",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Summarize default report to console:
  python summarize.py

  # Summarize a specific scan report:
  python summarize.py -i live_least_privilege_report.json

  # Focus only on IAM Users:
  python summarize.py --only-users

  # Focus only on Critical and High risks:
  python summarize.py --critical-only

  # Export the executive summary to Markdown:
  python summarize.py -i live_least_privilege_report.json --md summary_report.md

  # Export a standalone visual HTML dashboard:
  python summarize.py -i live_least_privilege_report.json --html dashboard.html
        """
    )
    parser.add_argument("-i", "--input", default="live_least_privilege_report.json",
                        help="Input report JSON file (default: live_least_privilege_report.json)")
    parser.add_argument("--only-users", action="store_true",
                        help="Filter out IAM roles and only display IAM users")
    parser.add_argument("--critical-only", action="store_true",
                        help="Only show principals with Critical/High privilege escalation or wildcard issues")
    parser.add_argument("--md", "--markdown", dest="md_output",
                        help="Export human-readable summary to a Markdown file")
    parser.add_argument("--html", dest="html_output",
                        help="Export a beautiful standalone visual HTML dashboard report")

    args = parser.parse_args()

    # Fallback to alternative filename if default not found
    if not os.path.exists(args.input) and args.input == "live_least_privilege_report.json":
        if os.path.exists("least_privilege_report.json"):
            args.input = "least_privilege_report.json"

    data = load_report(args.input)
    overview, principals = generate_summary(
        data,
        only_users=args.only_users,
        critical_only=args.critical_only
    )

    # Render console
    console_text = render_console(overview, principals)
    print(console_text)

    # Export to markdown if requested
    if args.md_output:
        md_text = render_markdown(overview, principals)
        with open(args.md_output, "w", encoding="utf-8") as f:
            f.write(md_text)
        print(f"\n[+] Báo cáo tóm tắt Markdown đã được lưu tại: {args.md_output}")

    # Export to HTML dashboard if requested
    if args.html_output:
        html_text = render_html(overview, principals)
        with open(args.html_output, "w", encoding="utf-8") as f:
            f.write(html_text)
        print(f"[+] Báo cáo Dashboard HTML trực quan đã được lưu tại: {args.html_output}")


if __name__ == "__main__":
    main()

